#!/usr/bin/env python3
"""Write the configuration parameter reference from DynEarthSol's own help.

    generate_parameter_reference.py --exe2d PATH --exe3d PATH --source REV [-o FILE]
    generate_parameter_reference.py --exe2d PATH --exe3d PATH --source REV --check

The executables are the authority: every option they accept is listed, with
its type, default and help text. Options whose default differs between 2D
and 3D show both. --check exits 1 when FILE is not what the executables
would produce, so a stale page can be caught after a solver change.
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

OPTION = re.compile(r'^  --(?P<name>[a-z_]+\.[A-Za-z0-9_]+) (?P<type>\S+)(?: \((?P<extra>.*)\))?$')
SECTIONS = {
    'sim': 'Model name, run length, output, checkpoints and restart.',
    'mesh': 'Domain size, mesh generation, resolution, quality checks and remeshing.',
    'markers': 'Lagrangian markers that carry material identity.',
    'control': 'Gravity, time stepping, mass scaling, damping, the PT solver, and heat and fluid transport.',
    'bc': 'Velocity, traction, thermal and hydraulic boundary conditions, and surface processes.',
    'ic': 'Initial temperature, stress, weak zones and material layout.',
    'mat': 'Rheology and material properties. List values hold one entry per material.',
    'monitor': 'Point monitors written as CSV time series.',
    'debug': 'Diagnostic output.',
}


def options(exe):
    """{name: (type, default or None, required, help)} in the order of `exe -h`."""
    text = subprocess.run([str(exe), '-h'], capture_output=True, text=True).stdout
    out, name = {}, None
    for line in text.splitlines():
        if line and not line.startswith(' '):
            name = None
            continue
        m = OPTION.match(line)
        if m:
            name = m['name']
            extra = m['extra'] or ''
            default = extra[1:] if extra.startswith('=') else None
            out[name] = [m['type'], default, extra == 'required', []]
        elif name and line.strip():
            out[name][3].append(line.strip())
    return {k: (t, d, r, ' '.join(h)) for k, (t, d, r, h) in out.items()}


def kind(type_, default):
    t = type_.split(':')[0]
    if t == 'TEXT':
        return 'list' if default and default.startswith('[') else 'text'
    return {'INT': 'integer', 'UINT': 'integer', 'FLOAT': 'real', 'BOOLEAN': 'yes/no'}.get(t, t.lower())


def show_default(default, required, type_):
    if required:
        return 'required'
    if default is None:
        return '–'
    if type_.startswith('BOOLEAN'):
        return {'0': 'no', '1': 'yes'}.get(default, default)
    return default


def cell(text):
    """Table-cell text that MDX renders literally."""
    text = text.replace('\\', '\\\\').replace('|', '\\|')
    text = text.replace('{', '\\{').replace('}', '\\}').replace('<', '&lt;').replace('>', '&gt;')
    return text.replace('*', '\\*').replace('_', '\\_')


def page(two, three, source):
    lines = ['---', 'sidebar_position: 2', 'slug: /reference/parameters', 'title: Configuration parameters',
             'description: Every DynEarthSol input parameter with its type, default and description.',
             'toc_max_heading_level: 2', '---', '',
             '{/* Generated by scripts/generate_parameter_reference.py; do not edit by hand. */}', '',
             '# Configuration parameters', '',
             f'All parameters accepted by DynEarthSol at source revision `{source}`, as printed by',
             '`dynearthsol2d -h` and `dynearthsol3d -h`. A parameter is written in its section',
             'of the input file; see [Configuration file](./configuration.md). Defaults that',
             'differ between 2D and 3D are shown for both.', '',
             'Types: *integer*, *real*, *yes/no*, *text*, and *list* (bracketed values, one per',
             'material where the parameter is per material; a single value applies to all).', '']
    names = list(two) + [n for n in three if n not in two]
    sections = []
    for n in names:
        s = n.split('.')[0]
        if s not in sections:
            sections.append(s)
    for s in sections:
        lines += [f'## `[{s}]`', '']
        if s in SECTIONS:
            lines += [SECTIONS[s], '']
        lines += ['| Parameter | Type | Default | Description |', '| --- | --- | --- | --- |']
        for n in names:
            if n.split('.')[0] != s:
                continue
            t2, d2, r2, h2 = two.get(n, three.get(n))
            t3, d3, r3, _ = three.get(n, (t2, d2, r2, h2))
            dflt = show_default(d2, r2, t2)
            if n not in three:
                dflt += ' (2D only)'
            elif n not in two:
                dflt = show_default(d3, r3, t3) + ' (3D only)'
            elif d3 != d2:
                dflt = f'2D: {dflt}<br/>3D: {show_default(d3, r3, t3)}'
            d = dflt if '<br/>' in dflt else cell(dflt)
            if '<br/>' in dflt:
                d = '<br/>'.join(cell(x) for x in dflt.split('<br/>'))
            lines.append(f'| `{n.split(".", 1)[1]}` | {kind(t2, d2)} | {d} | {cell(h2)} |')
        lines.append('')
    return '\n'.join(lines)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--exe2d', type=Path, required=True)
    p.add_argument('--exe3d', type=Path, required=True)
    p.add_argument('--source', required=True, help='DynEarthSol revision the executables were built from')
    p.add_argument('-o', '--output', type=Path,
                   default=Path(__file__).resolve().parents[1]/'docs/reference/parameters.md')
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    text = page(options(a.exe2d), options(a.exe3d), a.source)
    if a.check:
        current = a.output.read_text() if a.output.exists() else ''
        if current != text:
            sys.exit(f'{a.output} is out of date; rerun without --check')
        print(f'{a.output} is up to date')
        return
    a.output.write_text(text)
    print(f'wrote {a.output}')


if __name__ == '__main__':
    main()
